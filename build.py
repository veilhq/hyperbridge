"""Build Hyperbridge: concatenates CSS and emits per-module JS <script> blocks
into the inline HTML shell.

Each JS module is emitted as its own <script> block so a parse error in one
module does not abort the bundle. HyperKit (../.hyperkit/) supplies the shared
tokens, primitives and ecosystem JS; its content is prepended so app-local
styles override by cascade order and ecosystem globals (HvToast, etc.) exist
before app code runs. Missing HyperKit files fail the build loudly.

Usage: python build.py
Output: writes the HTML variable in generated_html.py
"""
import glob
import sys
from pathlib import Path

ROOT = Path(__file__).parent
HYPERKIT_DIR = ROOT.parent / ".hyperkit"
HYPERKIT_JS_DIR = HYPERKIT_DIR / "js"

sys.path.insert(0, str(HYPERKIT_DIR / "python"))
from hyperkit_css import hyperkit_css  # noqa: E402
from design_lint import report as report_design_lint  # noqa: E402

HYPERKIT_JS_MODULES = ["utils.js", "cursor-trail.js", "toast.js", "tooltip.js", "context-menu.js", "radial-menu.js", "cursor-box.js"]


def concat_files(pattern):
    files = sorted(glob.glob(str(ROOT / pattern)))
    return "\n".join(Path(f).read_text(encoding="utf-8") for f in files)


def render_hyperkit_js_blocks():
    """Emit one <script> block per HyperKit JS module, in load order."""
    blocks = []
    for name in HYPERKIT_JS_MODULES:
        f = HYPERKIT_JS_DIR / name
        if not f.exists():
            raise FileNotFoundError(
                f"HyperKit JS module missing: {f}\n"
                f"Hyperbridge's build.py expects all of {HYPERKIT_JS_MODULES} in .hyperkit/js/."
            )
        blocks.append(f"<!-- hyperkit/{name} -->\n<script>\n{f.read_text(encoding='utf-8')}\n</script>")
    return "\n".join(blocks)


def render_js_blocks():
    """Emit one <script> block per local JS module, in sorted order."""
    blocks = []
    for f in sorted(glob.glob(str(ROOT / "assets/js/*.js"))):
        name = Path(f).name
        blocks.append(f"<!-- {name} -->\n<script>\n{Path(f).read_text(encoding='utf-8')}\n</script>")
    return "\n".join(blocks)


def build():
    css = hyperkit_css(("cards", "components"), app="Hyperbridge") + "\n" + concat_files("assets/css/*.css")
    js_blocks = render_hyperkit_js_blocks() + "\n" + render_js_blocks()
    shell = (ROOT / "assets/shell.html").read_text(encoding="utf-8")
    html = shell.replace("{{CSS}}", css).replace("{{JS_BLOCKS}}", js_blocks)

    # repr() escapes every character so the module imports cleanly.
    out = ROOT / "generated_html.py"
    out.write_text(
        f'"""Auto-generated by build.py - do not edit."""\n\nHTML = {repr(html)}\n',
        encoding="utf-8",
    )
    print(f"Built: {len(css)} bytes CSS, {len(js_blocks)} bytes JS -> generated_html.py")


if __name__ == "__main__":
    report_design_lint("Hyperbridge", ROOT)  # exits 1 before anything is written
    build()
